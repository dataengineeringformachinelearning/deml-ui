#!/usr/bin/env node
/**
 * Rebuilds components/components.css from component folders.
 */
import fs from "node:fs";
import path from "node:path";
import { componentsDir, listComponents, CATEGORIES } from "./lib/components.mjs";

const outFile = path.join(componentsDir, "components.css");

const names = listComponents({ requireCss: true });
const formFieldCss = path.join(componentsDir, "form-field", "form-field.css");
const allCssNames = new Set(names);
if (fs.existsSync(formFieldCss)) allCssNames.add("form-field");

const assigned = new Set();
const lines = [
  `/* Component styles barrel — AUTO-GENERATED by scripts/generate-css-barrel.mjs`,
  `   Convention: components/<name>/<name>.html + <name>.css`,
  `   Do not edit by hand; run npm run sync`,
  `*/`,
  ``,
];

function addImports(title, list) {
  const present = list.filter((n) => allCssNames.has(n));
  if (!present.length) return;
  lines.push(`/* ${title} */`);
  for (const name of present) {
    lines.push(`@import url("./${name}/${name}.css");`);
    assigned.add(name);
  }
  lines.push(``);
}

for (const [category, order] of Object.entries(CATEGORIES)) {
  addImports(category, order);
}

const orphans = [...allCssNames]
  .filter((n) => !assigned.has(n))
  .sort((a, b) => a.localeCompare(b));
addImports("Other", orphans);

fs.writeFileSync(outFile, lines.join("\n"));
console.log(`Wrote components/components.css (${allCssNames.size} imports)`);
