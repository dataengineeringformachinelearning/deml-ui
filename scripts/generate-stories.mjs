#!/usr/bin/env node
/**
 * Generates comprehensive CSF3 stories per component under stories/<category>/.
 * Kits: scripts/lib/story-kits.mjs — Default, Playground, Variants, States, etc.
 */
import fs from "node:fs";
import path from "node:path";
import {
  root,
  componentsDir,
  listComponents,
  categorize,
  extractTemplate,
  toPascalCase,
  toStoryTitle,
  INTERACTIVE,
} from "./lib/components.mjs";
import { getStoryKit } from "./lib/story-kits.mjs";

const storiesDir = path.join(root, "stories");

function readHtml(name) {
  const htmlPath = path.join(componentsDir, name, `${name}.html`);
  if (!fs.existsSync(htmlPath)) return "";
  return fs.readFileSync(htmlPath, "utf8");
}

function slugCategory(category) {
  return category.toLowerCase().replace(/\s+/g, "-");
}

function serialize(value) {
  return JSON.stringify(value, null, 2).replace(/\n/g, "\n  ");
}

function writeStory(category, name) {
  const html = readHtml(name);
  if (!html) return false;

  const fragment = extractTemplate(html);
  const title = toStoryTitle(category, name);
  const kit = getStoryKit(name, category);
  const hasPlayDefault = INTERACTIVE.has(name);
  const dir = path.join(storiesDir, slugCategory(category));
  fs.mkdirSync(dir, { recursive: true });

  const modesImport =
    kit.chromaticModes === "layout"
      ? `import { layoutChromaticModes as chromaticModes } from "../../.storybook/modes.js";`
      : `import { defaultChromaticModes as chromaticModes } from "../../.storybook/modes.js";`;

  const lines = [
    `/* AUTO-GENERATED by scripts/generate-stories.mjs — do not edit by hand */`,
    `import { renderComponent, renderMarkup, renderBuilder, playComponent } from "../render.js";`,
    modesImport,
    ``,
    `export default {`,
    `  title: ${JSON.stringify(title)},`,
    `  tags: ["autodocs"],`,
    `  parameters: {`,
    `    layout: ${JSON.stringify(kit.layout || "fullscreen")},`,
    `    chromatic: {`,
    `      modes: chromaticModes,`,
    `      pauseAnimationAtEnd: true,`,
    `    },`,
    `    docs: {`,
    `      description: {`,
    `        component: ${JSON.stringify(
      `${kit.description}\n\nSource: \`components/${name}/\``
    )},`,
    `      },`,
    `      source: {`,
    `        language: "html",`,
    `        code: ${JSON.stringify(fragment)},`,
    `        type: "code",`,
    `      },`,
    `    },`,
    `    a11y: {`,
    `      test: "error",`,
    `    },`,
    `  },`,
  ];

  if (kit.argTypes) {
    lines.push(`  argTypes: ${serialize(kit.argTypes)},`);
  }
  if (kit.args) {
    lines.push(`  args: ${serialize(kit.args)},`);
  }

  lines.push(`};`, ``);

  const exportNames = [];

  for (const story of kit.stories) {
    const exportId = story.id.replace(/[^A-Za-z0-9_]/g, "") || "Story";
    exportNames.push(exportId);

    const usePlay = story.play === true || (story.kind === "demo" && hasPlayDefault && story.id === "Default");
    const storyParams = story.parameters
      ? `  parameters: ${serialize(story.parameters)},\n`
      : "";

    if (story.builder) {
      lines.push(
        `export const ${exportId} = {`,
        `  name: ${JSON.stringify(story.name)},`,
        storyParams,
        `  render: (args) => renderBuilder(${JSON.stringify(story.builder)}, args),`,
        `};`,
        ``
      );
      continue;
    }

    if (story.kind === "markup" && story.markup) {
      lines.push(
        `export const ${exportId} = {`,
        `  name: ${JSON.stringify(story.name)},`,
        storyParams,
        `  render: () => renderMarkup(${JSON.stringify(name)}, ${JSON.stringify(story.markup)}),`,
        ...(usePlay
          ? [
              `  play: async ({ canvasElement }) => {`,
              `    await playComponent(${JSON.stringify(name)}, canvasElement);`,
              `  },`,
            ]
          : []),
        `};`,
        ``
      );
      continue;
    }

    // demo — full component HTML
    lines.push(
      `export const ${exportId} = {`,
      `  name: ${JSON.stringify(story.name)},`,
      storyParams,
      `  render: () => renderComponent(${JSON.stringify(name)}),`,
      ...(usePlay
        ? [
            `  play: async ({ canvasElement }) => {`,
            `    await playComponent(${JSON.stringify(name)}, canvasElement);`,
            `  },`,
          ]
        : []),
      `};`,
      ``
    );
  }

  // Alias matching component PascalCase → Default (deep links / docs)
  if (exportNames.includes("Default")) {
    lines.push(`export const ${toPascalCase(name)} = Default;`, ``);
  }

  fs.writeFileSync(path.join(dir, `${name}.stories.js`), lines.join("\n"));
  return true;
}

function clearGeneratedStories() {
  if (!fs.existsSync(storiesDir)) return;
  for (const entry of fs.readdirSync(storiesDir, { withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith(".stories.js")) {
      fs.unlinkSync(path.join(storiesDir, entry.name));
    }
    if (entry.isDirectory() && entry.name !== "assets") {
      const dir = path.join(storiesDir, entry.name);
      for (const file of fs.readdirSync(dir)) {
        if (file.endsWith(".stories.js")) {
          fs.unlinkSync(path.join(dir, file));
        }
      }
    }
  }
}

const names = listComponents().filter((n) =>
  fs.existsSync(path.join(componentsDir, n, `${n}.html`))
);
const groups = categorize(names);

fs.mkdirSync(storiesDir, { recursive: true });
clearGeneratedStories();

let total = 0;
let storyCount = 0;
for (const [category, list] of Object.entries(groups)) {
  for (const name of list) {
    if (writeStory(category, name)) {
      total += 1;
      storyCount += getStoryKit(name, category).stories.length;
    }
  }
}

console.log(
  `Wrote ${total} component story files (${storyCount} named stories) across ${Object.keys(groups).length} groups → stories/`
);
